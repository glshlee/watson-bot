#!/usr/bin/env bash
# ==============================================================================
# Watson Pre-Push & Release Quality Gate (scripts/gate.sh)
# ADR-062: Dev/Prod Separation & Pre-Push Quality Gate
# ==============================================================================
set -eo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$DIR"

if [ "${SKIP_GATE:-0}" = "1" ]; then
    echo "⏭️  SKIP_GATE=1 감지됨: Pre-Push 품질 게이트를 건너뜁니다."
    exit 0
fi

VENV_BIN="$DIR/venv/bin"
RUFF="$VENV_BIN/ruff"
MYPY="$VENV_BIN/mypy"
PYTEST="$VENV_BIN/pytest"
if [ ! -x "$RUFF" ]; then RUFF="ruff"; fi
if [ ! -x "$MYPY" ]; then MYPY="mypy"; fi
if [ ! -x "$PYTEST" ]; then PYTEST="pytest"; fi

install_hook() {
    local hook_path="$DIR/.git/hooks/pre-push"
    mkdir -p "$(dirname "$hook_path")"
    cat << 'EOF' > "$hook_path"
#!/usr/bin/env bash
# Auto-generated by scripts/gate.sh --install-hook (ADR-062)
set -e
REPO_ROOT="$(git rev-parse --show-toplevel)"
exec "$REPO_ROOT/scripts/gate.sh"
EOF
    chmod +x "$hook_path"
    echo "✅ Git pre-push 훅이 성공적으로 설치되었습니다: $hook_path"
    exit 0
}

SMOKE_FLAG="--quick"
for arg in "$@"; do
    case "$arg" in
        --install-hook)
            install_hook
            ;;
        --full)
            SMOKE_FLAG="--full"
            ;;
        --quick|-q)
            SMOKE_FLAG="--quick"
            ;;
    esac
done

START_TS=$(date +%s)
echo "=================================================================="
echo "🚦 Watson Pre-Push 통합 품질 게이트 가동 (ADR-062)"
echo "=================================================================="

echo ""
echo "🔍 [Step 1/4] 정적 코드 린트 검사 (ruff check .)..."
"$RUFF" check .
echo "✅ [Step 1/4] Ruff 린트 통과!"

echo ""
echo "🔍 [Step 2/4] 정적 타입 무결성 검사 (mypy app/)..."
"$MYPY" app/
echo "✅ [Step 2/4] Mypy 타입 검사 통과!"

echo ""
echo "🧪 [Step 3/4] 전체 단위 테스트 실행 (pytest -q)..."
"$PYTEST" -q
echo "✅ [Step 3/4] Pytest 단위 테스트 전체 통과!"

echo ""
echo "🚀 [Step 4/4] 격리 샌드박스 스모크 테스트 (./scripts/smoke_test.sh $SMOKE_FLAG)..."
./scripts/smoke_test.sh "$SMOKE_FLAG"
echo "✅ [Step 4/4] 격리 샌드박스 스모크 테스트 통과!"

END_TS=$(date +%s)
ELAPSED=$((END_TS - START_TS))
echo ""
echo "=================================================================="
echo "🎉 모든 품질 게이트(4/4)를 무결점으로 통과했습니다! (소요 시간: ${ELAPSED}초)"
echo "=================================================================="
